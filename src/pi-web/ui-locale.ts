/** Pure localization of literal HTML template segments; no dynamic content is inspected. */
export function translateTemplateFragments(strings: readonly string[], lang: UiLanguage): string[] {
  if (lang === "en") return [...strings];
  const joined = strings.join(MARKER);
  const translated = joined
    .replace(/>([^<>]*)</g, (_, raw: string) => {
      const parts = raw.split(MARKER).map(part => {
        const begin = part.match(/^\s*/)?.[0] ?? "";
        const end = part.match(/\s*$/)?.[0] ?? "";
        const trimmed = part.trim();
        return trimmed ? begin + uiText(trimmed, lang) + end : part;
      });
      return ">" + parts.join(MARKER) + "<";
    })
    .replace(/\b(aria-label|placeholder|title|alt)=(["'])(.*?)\2/g,
      (_full, attr: string, quote: string, val: string) =>
        attr + "=" + quote + uiText(val, lang) + quote);
  const fragments = translated.split(MARKER);
  if (fragments.length !== strings.length) throw new Error("UI template interpolation count changed");
  return fragments;
}

const cache = new WeakMap<TemplateStringsArray, Map<UiLanguage, TemplateStringsArray>>();

/** Localize literal markup text and selected display attributes, preserving every bound value/handler. */
export function localizedTemplate<T extends (strings: TemplateStringsArray, ...values: any[]) => any>(html: T): T {
  return ((strings: TemplateStringsArray, ...values: unknown[]) => {
    const lang = displayLanguage();
    if (lang === "en") return html(strings, ...values);
    let perLanguage = cache.get(strings);
    if (!perLanguage) { perLanguage = new Map(); cache.set(strings, perLanguage); }
    let localized = perLanguage.get(lang);
    if (!localized) {
      const fragments = translateTemplateFragments(strings, lang);
      const result = [...fragments] as unknown as TemplateStringsArray;
      Object.defineProperty(result, "raw", {value: [...fragments], enumerable: false});
      localized = result;
      perLanguage.set(lang, localized);
    }
    return html(localized, ...values);
  }) as T;
}
