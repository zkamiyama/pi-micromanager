/** Browser-only display localization. Never translate IDs, permission values, or persisted contracts. */
export type UiLanguage = "ja" | "en";
export type UiLanguageChoice = UiLanguage | "auto";
const PREFERENCE_KEY = "pi-micromanager:ui-language:v1";
const MARKER = "\u001f";
let volatilePreference:UiLanguageChoice | undefined;

export function languageFor(
  choice: UiLanguageChoice, languages: readonly string[] | undefined, fallback?: string,
): UiLanguage {
  if (choice === "ja" || choice === "en") return choice;
  const primary = languages?.find(v => typeof v === "string" && v.trim()) ?? fallback ?? "";
  return /^ja(?:-|$)/i.test(primary) ? "ja" : "en";
}
export function languageChoice(): UiLanguageChoice {
  if (volatilePreference) return volatilePreference;
  try {
    const stored = localStorage.getItem(PREFERENCE_KEY);
    if (stored === "ja" || stored === "en" || stored === "auto") return stored;
  } catch { /* PI WEB may restrict local storage; browser locale still works. */ }
  return "auto";
}
export function setLanguageChoice(choice: UiLanguageChoice): void {
  if (choice !== "ja" && choice !== "en" && choice !== "auto") throw new Error("Unsupported display language");
  volatilePreference = choice;
  try { localStorage.setItem(PREFERENCE_KEY, choice); }
  catch { /* Keep an in-memory override when browser storage is unavailable. */ }
}
export function displayLanguage(): UiLanguage {
  const languages = typeof navigator === "undefined" ? undefined : navigator.languages;
  const fallback = typeof navigator === "undefined" ? undefined : navigator.language;
  return languageFor(languageChoice(), languages, fallback);
}

